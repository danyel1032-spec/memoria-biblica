// After `next build` (static export to out/), writes out/sw.js with every file
// precached, so the whole app, including the Bible text, works offline.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const OUT = "out";
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = "/" + relative(OUT, f).split("\\").join("/");
  if (rel === "/sw.js" || rel.endsWith(".map") || rel === "/_redirects" || rel === "/_headers") continue;
  hash.update(rel);
  hash.update(readFileSync(f));
  urls.push(rel.endsWith("/index.html") ? rel.slice(0, -"index.html".length) : rel);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/generate-sw.mjs. Do not edit.
const CACHE = "memoria-biblica-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Add one by one so a single failure does not block the rest.
      await Promise.all(PRECACHE.map((u) => cache.add(new Request(u, { cache: "reload" })).catch(() => {})));
      await self.skipWaiting();
    }),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("memoria-biblica-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === "navigate") {
    // Pages: same HTML regardless of ?query. Cache first, network as fallback.
    let path = url.pathname;
    if (!path.endsWith("/")) path += "/";
    event.respondWith(
      caches.match(path, { cacheName: CACHE }).then(
        (hit) => hit || fetch(req).catch(() => caches.match("/", { cacheName: CACHE })),
      ),
    );
    return;
  }

  event.respondWith(
    caches.match(url.pathname, { cacheName: CACHE, ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && url.pathname.startsWith("/_next/")) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(url.pathname, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
